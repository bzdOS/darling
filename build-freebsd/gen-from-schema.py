#!/usr/bin/env python3
"""gen-from-schema.py - darling.toml -> generated env files (stdlib only, python >= 3.11 for tomllib).

usage: gen-from-schema.py [--out DIR]           validate darling.toml against darling.schema.json, write ALL files into DIR only
       gen-from-schema.py --in-tree [--out DIR] same, but stub_data_names.py goes into the source tree (next to this
                                                script, overwrites the tracked file; warning on stderr), not into DIR
       gen-from-schema.py --check [--out DIR]   one line: SCHEMA-DRIFT pass files=N | SCHEMA-DRIFT FAIL <why>; exit 1 on FAIL
       gen-from-schema.py --emit keepone        print keepone.env to stdout (keep-one-check.sh fallback when not generated)
Files (in DIR, default: env DARLING_BUILD_DIR, else [env].DARLING_BUILD_DIR of the toml), and stub_data_names.py
(from [stubs]; tracked next to this script, stub_data_rules.DATA_NAMES comes from it). Without --in-tree it is written
into DIR like the others; --check always compares the tree copy against it (read-only):
  darling.env, keepone.env, run-<NAME>.env per [run.series.<NAME>].
Every file carries the sha256 of darling.toml, so an edit of the toml without regeneration is drift, as is a missing,
changed or orphaned (run-*.env without a toml entry) file. The validator is a minimal JSON Schema subset:
type, properties, required, additionalProperties, propertyNames, items, enum, minimum, maximum, minLength, pattern, $ref.
"""
import hashlib
import json
import os
import re
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
TOML = os.path.join(HERE, "darling.toml")
SCHEMA = os.path.join(HERE, "darling.schema.json")

TYPES = {
    "object": lambda v: isinstance(v, dict),
    "array": lambda v: isinstance(v, list),
    "string": lambda v: isinstance(v, str),
    "integer": lambda v: isinstance(v, int) and not isinstance(v, bool),
    "boolean": lambda v: isinstance(v, bool),
}


def resolve(root, s):
    while "$ref" in s:
        ref = s["$ref"]
        if not ref.startswith("#/"):
            raise ValueError("unsupported $ref " + ref)
        s = root
        for part in ref[2:].split("/"):
            s = s[part]
    return s


def validate(root, s, v, path, errs):
    s = resolve(root, s)
    t = s.get("type")
    if t and not TYPES[t](v):
        errs.append(f"{path}: not {t}")
        return
    if "enum" in s and v not in s["enum"]:
        errs.append(f"{path}: {v!r} not in {s['enum']}")
    if "minimum" in s and v < s["minimum"]:
        errs.append(f"{path}: {v} < {s['minimum']}")
    if "maximum" in s and v > s["maximum"]:
        errs.append(f"{path}: {v} > {s['maximum']}")
    if isinstance(v, str):
        if len(v) < s.get("minLength", 0):
            errs.append(f"{path}: shorter than {s['minLength']}")
        if "pattern" in s and not re.search(s["pattern"], v):
            errs.append(f"{path}: {v!r} does not match {s['pattern']}")
    if isinstance(v, list) and "items" in s:
        for i, x in enumerate(v):
            validate(root, s["items"], x, f"{path}[{i}]", errs)
    if isinstance(v, dict):
        props = s.get("properties", {})
        for k in s.get("required", []):
            if k not in v:
                errs.append(f"{path}: missing {k}")
        for k, x in v.items():
            if "propertyNames" in s:
                validate(root, s["propertyNames"], k, f"{path}.{k}(name)", errs)
            if k in props:
                validate(root, props[k], x, f"{path}.{k}", errs)
            else:
                ap = s.get("additionalProperties", True)
                if ap is False:
                    errs.append(f"{path}: unknown key {k}")
                elif isinstance(ap, dict):
                    validate(root, ap, x, f"{path}.{k}", errs)


def load():
    raw = open(TOML, "rb").read()
    data = tomllib.loads(raw.decode())
    schema = json.load(open(SCHEMA))
    errs = []
    validate(schema, schema, data, "$", errs)
    return data, hashlib.sha256(raw).hexdigest(), errs


def render(data, sha):
    head = f"# generated by gen-from-schema.py from darling.toml sha256={sha}; do not edit, edit darling.toml\n"
    out = {}
    out["darling.env"] = head + "".join(f"{k}={v}\n" for k, v in data["env"].items())
    ko = data["keepone"]
    out["keepone.env"] = (head + "KEEPONE_FILES='" + " ".join(ko["files"]) + "'\n"
                          + "KEEPONE_BACKUPS='" + " ".join(ko["backups"]) + "'\n")
    for name, r in data.get("run", {}).get("series", {}).items():
        kv = [("SERIES_PREFIX", r["prefix"]), ("SERIES_RUNS", r["runs"]), ("SERIES_TIMEOUT", r["timeout"]),
              ("CHROME_EXTRA_ARGS", r.get("chrome_extra_args", "")), ("DARLING_TRAP_LOG", r.get("trap_log", 1)),
              ("DARLING_KTRACE", r.get("ktrace", "")), ("DARLING_KTRACE_POINTS", r.get("ktrace_points", ""))]
        out[f"run-{name}.env"] = head + "".join(f"{k}='{v}'\n" for k, v in kv)
    return out


def render_tree(data, sha):
    """files generated into the source tree (next to this script, committed)"""
    st = data["stubs"]
    for p in st["patterns"]:
        re.compile(p)  # a bad pattern is a load error, not a broken generated module
    alts = (["_k(" + "|".join(st["k_prefixes"]) + ")[A-Z]"]
            + [re.escape(n) + "$" for n in st["exact"]] + list(st["patterns"]))
    py = (f'"""generated by gen-from-schema.py from darling.toml [stubs] sha256={sha}; do not edit, edit darling.toml"""\n'
          "import re\n\n"
          f"K_PREFIXES = {tuple(st['k_prefixes'])!r}\n"
          f"EXACT = {tuple(st['exact'])!r}\n"
          f"PATTERNS = {tuple(st['patterns'])!r}\n"
          f"DATA_NAMES = re.compile({'^(' + '|'.join(alts) + ')'!r})\n")
    return {"stub_data_names.py": py}


def main(argv):
    mode, outdir, emit, in_tree = "gen", None, None, False
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--check":
            mode = "check"
        elif a == "--in-tree":
            in_tree = True
        elif a == "--out" and i + 1 < len(argv):
            i += 1; outdir = argv[i]
        elif a == "--emit" and i + 1 < len(argv) and argv[i + 1] == "keepone":
            i += 1; mode = "emit"
        else:
            print(__doc__.strip().splitlines()[2], file=sys.stderr); return 2
        i += 1
    tag = "SCHEMA-DRIFT FAIL" if mode == "check" else "GEN FAIL"
    try:
        data, sha, errs = load()
    except Exception as e:  # unreadable or unparsable toml/schema
        print(f"{tag} load: {e}"); return 1
    if errs:
        print(f"{tag} schema: " + "; ".join(errs[:5])); return 1
    try:
        files = render(data, sha)
        tree = render_tree(data, sha)
    except re.error as e:
        print(f"{tag} schema: $.stubs.patterns: {e}"); return 1
    if mode == "emit":
        sys.stdout.write(files["keepone.env"]); return 0
    outdir = outdir or os.environ.get("DARLING_BUILD_DIR") or data["env"]["DARLING_BUILD_DIR"]
    paths = {os.path.join(outdir, n): t for n, t in files.items()}
    tdir = HERE if (in_tree or mode == "check") else outdir
    paths.update({os.path.join(tdir, n): t for n, t in tree.items()})
    if mode == "check":
        bad = []
        for p, txt in paths.items():
            n = os.path.basename(p)
            if not os.path.isfile(p):
                bad.append(f"missing:{n}")
            elif open(p).read() != txt:
                bad.append(f"differs:{n}")
        for n in sorted(os.listdir(outdir)) if os.path.isdir(outdir) else []:
            if re.fullmatch(r"run-.+\.env", n) and n not in files:
                bad.append(f"orphan:{n}")
        if bad:
            print("SCHEMA-DRIFT FAIL " + " ".join(bad) + " (run gen-from-schema.py --in-tree)"); return 1
        print(f"SCHEMA-DRIFT pass files={len(paths)}"); return 0
    os.makedirs(outdir, exist_ok=True)
    for p, txt in paths.items():
        if os.path.dirname(p) == HERE:
            print(f"WARNING: --in-tree: writing source tree file {p}", file=sys.stderr)
        tmp = p + ".tmp"
        with open(tmp, "w") as f:
            f.write(txt)
        os.replace(tmp, p)
    print(f"GEN ok files={len(paths)} dir={outdir} tree={','.join(tree)}@{tdir}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

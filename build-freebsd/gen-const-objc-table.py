#!/usr/bin/env python3
"""gen-const-objc-table.py OVERLAY OUT.h -- the string constants of the stub images, as a C table for const-objc-probe.c.

Every stub image of the overlay (check-data-as-code.py --list-stubs: the generated stubs and the images with their
own generators) is read; each exported data symbol that stub_data_rules.is_string_const() calls a string constant is
listed as { install path, symbol, nonzero }. nonzero is 1 when the 8 bytes in the file are not zero (a CFString
pointer); a zero one is set at run time (a hand written constructor) or is a hole, the probe validates it only when
the loaded value is not NULL.
"""
import os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stub_data_rules as R
from importlib.machinery import SourceFileLoader

here = os.path.dirname(os.path.abspath(__file__))
cid = SourceFileLoader("cid", os.path.join(here, "check-import-data.py")).load_module()
ov = sys.argv[1].rstrip("/")
out = sys.argv[2]
env = dict(os.environ)
env.pop("CHROME_APP", None)
stubs = subprocess.run([sys.executable, os.path.join(here, "check-data-as-code.py"), "--overlay", ov, "--list-stubs"],
                       capture_output=True, text=True, env=env).stdout.split()
rows = []
for p in sorted(stubs):
    img = cid.Img(p)
    inst = "/" + os.path.relpath(p, ov)
    for name, (addr, seg) in sorted(img.exp.items()):
        if R.is_string_const(name) and seg.startswith("__DATA"):
            rows.append((inst, name[1:], 1 if img.read8(addr) else 0))
with open(out, "w") as f:
    f.write("/* generated by gen-const-objc-table.py */\nstatic const struct { const char *image, *sym; int nonzero; } tab[] = {\n")
    for r in rows:
        f.write('\t{ "%s", "%s", %d },\n' % r)
    f.write("\t{ 0, 0, 0 }\n};\n")
with open(out + ".libs", "w") as f:   # the images the table names: linked into the probe so the launcher stages their closure
    for i in sorted({r[0] for r in rows}):
        ident = subprocess.run(["llvm-objdump", "--macho", "--dylib-id", ov + i], capture_output=True, text=True).stdout.split()
        if i in ident:   # an image whose id differs from its path would add a dependency nothing can load
            f.write(ov + i + "\n")
print("const-objc-table: %d constants (%d nonzero) in %d images" % (
    len(rows), sum(r[2] for r in rows), len({r[0] for r in rows})))

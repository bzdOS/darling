#!/bin/sh
# Build darlingserver on FreeBSD 15.1 (standalone, without full Darling cmake tree).
# Usage: sh build-freebsd/build-darlingserver.sh
# Requires: pkg install cmake llvm epoll-shim
#
# Environment:
#   DARLING_BUILD_DIR  — where build artefacts go (required, no default: darling.toml [env])
#   DARLING_SRC_DIR    — root of this repository  (default: directory of this script/..)

set -eu
# apply build-freebsd/patches/series to the submodule trees (idempotent; fails the build on conflict)
sh "$(dirname "$0")/apply-patches.sh" || exit 1

SCRIPT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
BUILD="${DARLING_BUILD_DIR:?set DARLING_BUILD_DIR (darling.toml [env])}/dserver"
DS="${DARLING_SRC_DIR:-${SCRIPT_DIR}}/src/external/darlingserver"
# darlingserver RPC wrappers: generated into the build directory, never into the source tree
DRPC="${DARLING_BUILD_DIR:?set DARLING_BUILD_DIR (darling.toml [env])}/dserver/generated-rpc"
python3 "${DS}/scripts/generate-rpc-wrappers.py" "${DRPC}/include/darlingserver/rpc.h" \
  "${DRPC}/internal-include/darlingserver/rpc.internal.h" "${DRPC}/src/rpc.c" '"../include/darlingserver/rpc.h"' || exit 1
SRC="${DARLING_SRC_DIR:-${SCRIPT_DIR}}/src"
COMPAT="${SRC}/startup/compat-includes"
DTAPE_LIB="${DARLING_BUILD_DIR:?set DARLING_BUILD_DIR (darling.toml [env])}/dtape/dtape-build/libdtape.a"

# Build in a subdirectory of our own rather than wiping ${BUILD}: that
# directory is shared with build-mldr-only.sh, which installs its binary to
# ${BUILD}/mldr-real/mldr. Wiping it deleted mldr outright, so the two scripts
# only worked in one order — and getting the order wrong left no error, just a
# missing mldr at the next test run. Scoping the clean to our own scratch
# directory removes the ordering dependency instead of documenting it.
SCRATCH="${BUILD}/dserver-build"

# Guards: cmake must never run anywhere but in ${SCRATCH} (an earlier non-sudo
# run failed rm -rf on a root-owned dir, the && chain fell through and cmake
# overwrote the tracked CMakeLists.txt in the repo root).
SRC_ROOT="$(cd "${DARLING_SRC_DIR:-${SCRIPT_DIR}}" && pwd -P)"
for d in "${BUILD}" "${SCRATCH}"; do
    if [ -e "$d" ] && [ ! -w "$d" ]; then
        echo "ERROR: $d exists and is not writable by $(id -un); run under sudo" >&2
        exit 1
    fi
done
mkdir -p "${BUILD}"
BUILD_REAL="$(cd "${BUILD}" && pwd -P)" || exit 1
SCRATCH_REAL="${BUILD_REAL}/dserver-build"
case "${SCRATCH_REAL}/" in
    "${SRC_ROOT}/") echo "ERROR: build dir is the repo root: ${SCRATCH_REAL}" >&2; exit 1 ;;
    "${SRC_ROOT}/build-freebsd/"*) ;;  # the intended in-tree build location
    "${SRC_ROOT}/"*) echo "ERROR: build dir is inside the source tree: ${SCRATCH_REAL}" >&2; exit 1 ;;
esac
rm -rf "${SCRATCH}"
mkdir -p "${SCRATCH}"
cd "${SCRATCH}" || exit 1
if [ "$(pwd -P)" != "${SCRATCH_REAL}" ] || [ "$(pwd -P)" = "${SRC_ROOT}" ]; then
    echo "ERROR: cwd $(pwd -P) is not the intended build dir ${SCRATCH_REAL}" >&2
    exit 1
fi

# rtsig.h is normally generated by the startup/rtsig binary
printf '#define LINUX_SIGRTMIN %d\n#define LINUX_SIGRTMAX %d\n' 65 126 > rtsig.h

cat > CMakeLists.txt << CMEOF
cmake_minimum_required(VERSION 3.13)
project(darlingserver CXX C)

set(CMAKE_C_FLAGS   "\${CMAKE_C_FLAGS}   -std=gnu11  -ggdb -O0")
set(CMAKE_CXX_FLAGS "\${CMAKE_CXX_FLAGS} -std=c++17  -ggdb -O0")

set(DS   ${DS})
set(SRC  ${SRC})
set(DRPC ${DRPC})
set(COMPAT ${COMPAT})

set(CMAKE_INSTALL_PREFIX "/usr/local")
set(CMAKE_INSTALL_LIBDIR "lib")
set(SUFFIX "")
set(GIT_BRANCH "pr-arm64")
set(GIT_COMMIT_HASH "freebsd-port")
configure_file(
  \${SRC}/include/darling-config.h.in
  \${CMAKE_BINARY_DIR}/darling-config.h
)

include_directories(
  \${COMPAT}
  \${SRC}/startup/xlate
  /usr/local/include/libepoll-shim
  \${DS}/include
  \${DS}/internal-include
  \${DS}/duct-tape/include
  \${DRPC}/include
  \${DRPC}/internal-include
  \${SRC}/libsimple/include
  \${CMAKE_BINARY_DIR}
)

add_definitions(
  -D_GNU_SOURCE
  -DDARLING_FREEBSD
  -DLIBSIMPLE_FREEBSD=1
  -DDSERVER_SINGLE_THREADED=1
)

# Support library: libsimple lock + FreeBSD POSIX compat (eventfd, timerfd)
add_library(simple STATIC
  \${SRC}/libsimple/src/lock.c
  \${SRC}/startup/bsdos_posix_compat.c
)
target_include_directories(simple PUBLIC
  \${SRC}/libsimple/include
  \${COMPAT}
)
target_compile_definitions(simple PUBLIC LIBSIMPLE_FREEBSD=1)

# Prebuilt duct-tape (real XNU Mach IPC emulation, replaces dtape_stubs.c)
add_library(dtape STATIC IMPORTED)
set_target_properties(dtape PROPERTIES
  IMPORTED_LOCATION ${DTAPE_LIB}
)

set(DS_SRCS
  \${DS}/src/utility.cpp
  \${DS}/src/registry.cpp
  \${DS}/src/darlingserver.cpp
  \${DS}/src/message.cpp
  \${DS}/src/server.cpp
  \${DS}/src/process.cpp
  \${DS}/src/thread.cpp
  \${DS}/src/logging.cpp
  \${DS}/src/call.cpp
  \${DS}/src/async-writer.cpp
  \${DS}/src/kqchan.cpp
  \${DS}/src/stack-pool.cpp
)

add_executable(darlingserver \${DS_SRCS})
target_link_libraries(darlingserver simple dtape -L/usr/local/lib -lepoll-shim -lutil -ljail -lpthread -lc++)
CMEOF

cmake .
make -j${JOBS:-$(( $(sysctl -n hw.ncpu) - 2 ))}
# Publish the binary at the canonical path everything else reads from; the
# scratch directory above is an implementation detail of this script.
# ${BUILD}/darlingserver may be a symlink to the scratch binary (same file): install(1) refuses that
# (rc=64), and nothing needs copying. A real failure still aborts under set -e.
if [ "${SCRATCH}/darlingserver" -ef "${BUILD}/darlingserver" ]; then
    chmod 755 "${SCRATCH}/darlingserver"
else
    install -m 755 "${SCRATCH}/darlingserver" "${BUILD}/darlingserver"
fi

echo "=== Built: ${BUILD}/darlingserver ==="
ls -lh "${BUILD}/darlingserver"

# mldr is built separately by build-mldr-only.sh (the complete recipe: includes
# freebsd_syscall_trap.c, elfcalls.c, threads.c and generates darling-config.h).
# This script used to also build an mldr here, but that copy predated
# freebsd_syscall_trap.c and had drifted into a stale, incomplete duplicate
# that `rm -rf`'d and clobbered build-mldr-only.sh's output. Removed — run
# build-mldr-only.sh after this script instead.

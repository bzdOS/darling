#!/bin/sh
# chrome-series.sh - N-run Chrome series with an md5 gate and a one-line SERIES summary.
# usage: chrome-series.sh --core-selftest   (no Chrome: segfaulting sudo process x2, checks core written and only newest kept)
# usage: chrome-series.sh PREFIX N [TIMEOUT]    logs: $DARLING_BUILD_DIR/chrome-sr-<PREFIX>*.log
# Env: DARLING_SRC_DIR DARLING_OVERLAY DARLING_BUILD_DIR CHROME_APP (as for chrome-sr-batch.sh);
#      EXPECT_MLDR_MD5  if set and different from the installed mldr, exit 1 before running.
#      env-preflight.sh runs first (EXPECT_DSERVER_MD5, PREFLIGHT_MAX_LOAD, PREFLIGHT_PROBE=0, PREFLIGHT_IGNORE); exit 1 on fail.
#      stage-gate.sh runs after the preflight: STAGECHK line, exit 1 on a built/overlay/staged md5 mismatch.
#      CHROME_EXTRA_ARGS  extra Chrome flags (exported to chrome-sr-batch.sh, inserted before the URL).
# Valid run = has GUEST-EXEC. survived20 = valid runs with WRAPPER_DURATION > 20. top = most frequent WRAPPER_RC.
# Before it: FWDMISS <unique -[Class sel] of the runs' OBJC-FWD-MISS lines, comma separated> (or FWDMISS none).
#      Each rc124 run is followed by its NOWINDOW-DIAG line (nowindow-diag.sh analyze).
# Last line: SERIES <prefix> N=<n> valid=<v> survived20=<k> top=rc<code>x<count> windows=<runs with windows> fwdmiss=<unique OBJC-FWD-MISS selectors> mldr=<md5>
# Also written to $SERIES_SUMMARY_DIR/<prefix>.txt (default <parent of the build dir>/series-summaries) with a per-run table; a run whose
#      sway was not healthy afterwards is RUN-INVALID (not counted, retried). CHROME_APP defaults to the CfT bundle, missing -> SERIES-ABORT reason=chrome-app.
# Exit 1 if the gate fails or valid=0.
# The batch runs in the background and is waited for by pid (kill -0, SERIES_PIDWAIT_MAX s, default N*(TIMEOUT+600)+600; then killed, SERIES-PIDWAIT-TIMEOUT line).
# Very last line: SERIES-EXIT rc=<n> pid=<series pid> (after LEFTOVER); watchers wait on it instead of pgrep -f.
#      chrome-series.sh --dump-selftest   (no Chrome: fake launcher + fake dump scripts, checks the rc124 hang dump)
#      CHROME_SR_SERVER_LOG=debug  server runs with DSERVER_LOG_LEVEL=debug; its log is saved as chrome-sr-<run>-dserver.txt
#      Hang dump (rc124 runs): chrome-sr-<run>-dsdump.txt / -guest.txt, taken CHROME_SR_DUMP_LEAD (40) s before the timeout, CHROME_SR_DUMP=0 off.
#      chrome-series.sh --series NAME   the preset [run.series.NAME] of darling.toml: reads (as data, never sourced) the node
#      env file DARLING_ENV_FILE (default /opt/darling/build/darling.env; a variable already set in the env wins) and then
#      run-NAME.env from DARLING_BUILD_DIR (both generated by gen-from-schema.py), then runs as PREFIX N TIMEOUT with its
#      CHROME_EXTRA_ARGS DARLING_TRAP_LOG DARLING_KTRACE DARLING_KTRACE_POINTS. Missing file or key: SERIES-ABORT reason=series.
if [ "$1" = "--series" ]; then
	_sn=${2:?--series NAME}
	_ef="${DARLING_ENV_FILE:-/opt/darling/build/darling.env}"
	[ -f "$_ef" ] || { echo "SERIES-ABORT reason=series no $_ef"; exit 1; }
	while IFS= read -r _l; do
		_k=${_l%%=*}; _v=${_l#*=}; _v=${_v#\"}; _v=${_v%\"}; _v=${_v#\'}; _v=${_v%\'}
		case "$_k" in
		DARLING_SRC_DIR|DARLING_BUILD_DIR|DARLING_OVERLAY|KEEPONE_ROOT|DARLING_DISK_MAX|PROBE_TIMEOUT)
			eval "[ -n \"\${$_k}\" ] || $_k=\$_v; export $_k";;
		esac
	done <"$_ef"
	_rf="${DARLING_BUILD_DIR:?}/run-$_sn.env"
	[ -f "$_rf" ] || { echo "SERIES-ABORT reason=series no $_rf (run gen-from-schema.py)"; exit 1; }
	SERIES_PREFIX=; SERIES_RUNS=; SERIES_TIMEOUT=
	while IFS= read -r _l; do
		_k=${_l%%=*}; _v=${_l#*=}; _v=${_v#\'}; _v=${_v%\'}
		case "$_k" in
		SERIES_PREFIX|SERIES_RUNS|SERIES_TIMEOUT) eval "$_k=\$_v";;
		CHROME_EXTRA_ARGS|DARLING_TRAP_LOG|DARLING_KTRACE|DARLING_KTRACE_POINTS) eval "$_k=\$_v; export $_k";;
		esac
	done <"$_rf"
	[ -n "$SERIES_PREFIX" ] && [ -n "$SERIES_RUNS" ] && [ -n "$SERIES_TIMEOUT" ] || { echo "SERIES-ABORT reason=series bad $_rf"; exit 1; }
	[ -n "$DARLING_KTRACE" ] || unset DARLING_KTRACE
	[ -n "$DARLING_KTRACE_POINTS" ] || unset DARLING_KTRACE_POINTS
	set -- "$SERIES_PREFIX" "$SERIES_RUNS" "$SERIES_TIMEOUT"
fi
# --core-selftest: sudo process that segfaults twice under the core-wrap.sh setup; checks a core appears and only the newest is kept
if [ "$1" = "--core-selftest" ]; then
	CORE_DIR=$(mktemp -d "${TMPDIR:-/tmp}/core-selftest.XXXXXX") || exit 1
	export CORE_DIR CORE_LIMIT_KB=${CORE_LIMIT_KB:-2097152}
	W=$(cd "$(dirname "$0")" && pwd)/core-wrap.sh
	# the core name is %N (process name), so use two names for the two crashes
	for i in 1 2; do cp /bin/sh "$CORE_DIR/crasher$i"; sudo -n env CORE_DIR="$CORE_DIR" CORE_LIMIT_KB="$CORE_LIMIT_KB" sh "$W" run "$CORE_DIR/crasher$i" -c 'kill -SEGV $$' 2>/dev/null; sleep 1; done
	n=$(ls "$CORE_DIR"/*.core 2>/dev/null | wc -l)
	out=$(sh "$W" prune); m=$(ls "$CORE_DIR"/*.core 2>/dev/null | wc -l)
	sudo -n rm -rf "$CORE_DIR"
	if [ "$n" -ge 2 ] && [ "$m" -eq 1 ]; then echo "CORE-SELFTEST pass (cores before=$n after_prune=$m limit_kb=$CORE_LIMIT_KB)"; exit 0; fi
	echo "CORE-SELFTEST fail (cores before=$n after_prune=$m) $out"; exit 1
fi
# --dump-selftest: fake launcher (a fake server and a fake guest that never exit) and fake dump scripts; runs
# chrome-wl-run.sh with a 8 s timeout and checks: rc 124, dump scripts called with exactly the fake server pid and
# guest pid, their output saved beside the log, CHROME_SR_SERVER_LOG passed as DSERVER_LOG_LEVEL, dserver.log copied.
if [ "$1" = "--dump-selftest" ]; then
	W=$(cd "$(dirname "$0")" && pwd)
	: "${DARLING_SRC_DIR:=$(cd "$W/.." && pwd)}"; export DARLING_SRC_DIR
	TD=$(mktemp -d "${TMPDIR:-/tmp}/dump-selftest.XXXXXX") || exit 1
	cat > "$TD/launch" <<'FAKE'
#!/bin/sh
sleep 600 &
SP=$!
trap 'kill $SP 2>/dev/null; exit 143' TERM
mkdir -p "$DARLING_PREFIX/private/var/log"
echo "level=$DSERVER_LOG_LEVEL" > "$DARLING_PREFIX/private/var/log/dserver.log"
echo "[launch] DSERVER pid=$SP" >&2
echo "[launch] STAGING end / GUEST-EXEC pid=$$ t=0s" >&2
# orphan: a grandchild that ignores TERM and is not killed by the trap above
# (like a guest helper whose parent dies); timeout must still reap it
( trap "" TERM; exec sleep 600 ) &
echo "$SP $$ $!" > "$FAKE_PIDS"
while :; do sleep 1; done
FAKE
	printf '#!/bin/sh\necho "ds called pid=$1 n=$#" >> "%s"; echo "FAKE-DSDUMP $1"\n' "$TD/calls" > "$TD/dsdump"
	printf '#!/bin/sh\necho "guest called pid=$1 log=$2 n=$#" >> "%s"; echo "FAKE-GUEST $1"\n' "$TD/calls" > "$TD/guest"
	chmod 755 "$TD/launch"; : > "$TD/pids"; : > "$TD/calls"; chmod 666 "$TD/pids" "$TD/calls"
	mkdir -p "$TD/xdg"
	( DARLING_BUILD_DIR="$TD" DARLING_OVERLAY=/nonexistent CHROME_APP=/nonexistent XDG_RUNTIME_DIR="$TD/xdg" WAYLAND_DISPLAY=w \
	  CHROME_ARGS=x CORE_DIR= CHROME_LOG_PREFIX=chrome-sr CHROME_SR_LAUNCH="$TD/launch" CHROME_SR_DSDUMP="$TD/dsdump" \
	  CHROME_SR_GUESTSNAP="$TD/guest" CHROME_SR_DUMP_LEAD=4 CHROME_SR_SERVER_LOG=debug \
	  sh "$W/chrome-wl-run.sh" st1 8 FAKE_PIDS="$TD/pids" FAKE_CALLS="$TD/calls" >/dev/null 2>&1 )
	SP=$(cut -d' ' -f1 "$TD/pids"); GP=$(cut -d' ' -f2 "$TD/pids")
	L=$TD/chrome-sr-st1.log; ok=1; why=""
	chk() { eval "$1" || { ok=0; why="$why [$2]"; }; }
	OP=$(cut -d' ' -f3 "$TD/pids")
	chk '[ -n "$OP" ] && ! ps -p "$OP" >/dev/null 2>&1' orphan-reaped
	chk 'grep -aq "^WRAPPER_RC=124" "$L"' rc124
	chk '[ -n "$SP" ] && [ -n "$GP" ] && [ "$SP" != "$GP" ]' pids
	chk '[ "$(grep -c "^ds called" "$TD/calls")" = 1 ] && grep -q "^ds called pid=$SP n=1$" "$TD/calls"' ds-called-with-server-pid
	chk '[ "$(grep -c "^guest called" "$TD/calls")" = 1 ] && grep -q "^guest called pid=$GP log=$L n=2$" "$TD/calls"' guest-called-with-guest-pid
	chk 'grep -q "FAKE-DSDUMP $SP" "$TD/chrome-sr-st1-dsdump.txt"' dsdump-saved
	chk 'grep -q "FAKE-GUEST $GP" "$TD/chrome-sr-st1-guest.txt"' guest-saved
	chk 'grep -q "^level=debug" "$TD/chrome-sr-st1-dserver.txt"' dserver-log-saved
	chk 'grep -aq "^HANGDUMP server=$SP guest=$GP" "$L"' hangdump-line
	chk '! ls /tmp/darling-run.* >/dev/null 2>&1 || ! kill -0 "$SP" 2>/dev/null' fake-server-gone
	sudo -n kill -9 "$SP" 2>/dev/null; sudo -n rm -rf "$TD"
	if [ $ok -eq 1 ]; then echo "DUMP-SELFTEST pass (rc=124 server_pid=$SP guest_pid=$GP dumps called once each with those pids, outputs and dserver.log saved)"; exit 0; fi
	echo "DUMP-SELFTEST fail:$why"; exit 1
fi
# exclusive run lock: one probe/Chrome run at a time; nested calls (DARLING_LOCK_HELD) do not re-lock
if [ -z "$DARLING_LOCK_HELD" ]; then
	: "${DARLING_BUILD_DIR:?}"
	# run a private snapshot: sh reads a script incrementally, so editing this file mid-run broke the parse
	SNAP=$(mktemp "${TMPDIR:-/tmp}/chrome-series.XXXXXX") || exit 1
	cp "$0" "$SNAP"
	DARLING_LOCK_HELD=1 lockf -t 0 "$DARLING_BUILD_DIR/.darling-run.lock" sh "$SNAP" "$@"
	rc=$?
	rm -f "$SNAP"
	[ $rc -eq 75 ] && { echo "LOCK busy"; exit 1; }
	exit $rc
fi
# On every exit: count darlingservers of our prefixes (this launcher's unique /tmp/darling-run.* or the
# old fixed one); print LEFTOVER dservers=<n> last and exit 1 if n>0.
leftover_report() {
	_rc=$?
	type cores_prune >/dev/null 2>&1 && cores_prune
	LEFT=$(ps -axww -o pid,command | awk '$2 ~ /(^|\/)darlingserver$/ && ($3 ~ /^\/tmp\/darling-run\./ || $3 == "/tmp/darling-dynamic-smoke-fresh") {n++} END{print n+0}')
	echo "LEFTOVER dservers=$LEFT"
	[ "$LEFT" -eq 0 ] || _rc=1
	# stale mldr RPC sockets of dead pids (older than 30 min); live ones are kept
	sh "$DARLING_SRC_DIR/build-freebsd/keep-one-check.sh" --clean-sockets 2>&1 || true
	echo "SERIES-EXIT rc=$_rc pid=$$"
	exit $_rc
}
# BEGIN series_pidwait
# series_pidwait PID MAX_SECONDS: 0 when PID is gone (or a zombie), 124 after MAX_SECONDS; liveness = kill -0
series_pidwait() {
	_wp=$1; _wm=$2; _ws=0
	while kill -0 "$_wp" 2>/dev/null && [ "$(ps -o stat= -p "$_wp" 2>/dev/null | cut -c1)" != Z ]; do
		[ "$_ws" -ge "$_wm" ] && return 124
		sleep 1; _ws=$((_ws+1))
	done
	return 0
}
# END series_pidwait
trap leftover_report EXIT
export CHROME_EXTRA_ARGS; P=${1:?}; N=${2:?}; T=${3:-120}
: "${DARLING_SRC_DIR:?}" "${DARLING_BUILD_DIR:?}"
# CHROME_APP default: the CfT bundle (without it every run is invalid, valid=0); a path that does not exist aborts loudly
CHROME_APP=${CHROME_APP:-$(dirname "$DARLING_BUILD_DIR")/chrome-cft/chrome-mac-x64/Google Chrome for Testing.app}; export CHROME_APP
. "$DARLING_SRC_DIR/build-freebsd/series-count.sh"
if [ ! -d "$CHROME_APP" ]; then
	_l="SERIES-ABORT reason=chrome-app path=\"$CHROME_APP\""; echo "$_l"
	series_summary_write "$DARLING_BUILD_DIR" "$P" "$N" "$_l"; exit 1
fi
: "${DARLING_SRC_DIR:?}" "${DARLING_BUILD_DIR:?}"
# Core files (a Mach core can be 14 GB): sudo resets the core limit to 0, so chrome-wl-run.sh runs the guest via
# core-wrap.sh, which sets ulimit -c to CORE_LIMIT_KB (default and maximum 2 GiB) and cds to CORE_DIR
# (default $DARLING_BUILD_DIR/cores; kern.corefile %N.core lands in the cwd). At exit only the newest core is
# kept, older ones are deleted (CORES line shows it). Delete the kept one after use.
export CORE_LIMIT_KB=${CORE_LIMIT_KB:-2097152} CORE_DIR=${CORE_DIR:-$DARLING_BUILD_DIR/cores}
cores_prune() { sh "$DARLING_SRC_DIR/build-freebsd/core-wrap.sh" prune; }
MLDR=$DARLING_BUILD_DIR/dserver/mldr-real/mldr
DS=$DARLING_BUILD_DIR/dserver/darlingserver
M=$(md5 -q "$MLDR" 2>/dev/null || md5sum "$MLDR" | cut -d' ' -f1)
D=$(md5 -q "$DS" 2>/dev/null || md5sum "$DS" | cut -d' ' -f1)
echo "mldr md5=$M"; echo "darlingserver md5=$D"
# environment preflight (leftover servers, dserver md5, load, N=1 probe); see env-preflight.sh
sh "$DARLING_SRC_DIR/build-freebsd/env-preflight.sh" || exit 1
# md5 gate: built vs overlay vs staged copy of mldr and every rebuilt stub image (stage-gate.sh); mismatch -> exit 1
STAGE_GATE_KEEPONE=1 sh "$DARLING_SRC_DIR/build-freebsd/stage-gate.sh" || exit 1
if [ -n "$EXPECT_MLDR_MD5" ] && [ "$EXPECT_MLDR_MD5" != "$M" ]; then
	echo "GATE FAIL: expected mldr md5 $EXPECT_MLDR_MD5, installed $M"; exit 1
fi
# disk guard: one threshold, refuse to start at >= SERIES_DISK_MAX (default DARLING_DISK_MAX, else 85) % root use
# (the batch loop stops at the same value, SERIES_DISK_STOP default 85, see chrome-sr-batch.sh)
DISK_USE=$(df -P / | awk 'NR==2{gsub("%","",$5); print $5+0}')
[ "$DISK_USE" -ge "${SERIES_DISK_MAX:-${DARLING_DISK_MAX:-85}}" ] && { echo "SERIES-ABORT reason=disk use=${DISK_USE}%"; exit 1; }
# was a foreground call; now background + wait by pid (the batch's own per-run timeouts still apply, this is the outer bound)
SERIES_PIDWAIT_MAX=${SERIES_PIDWAIT_MAX:-$((N*(T+600)+600))}
sh "$DARLING_SRC_DIR/build-freebsd/chrome-sr-batch.sh" "$P" "$N" "$T" &
BP=$!
series_pidwait "$BP" "$SERIES_PIDWAIT_MAX" || { echo "SERIES-PIDWAIT-TIMEOUT pid=$BP after=${SERIES_PIDWAIT_MAX}s"; kill -TERM "$BP" 2>/dev/null; sleep 5; kill -KILL "$BP" 2>/dev/null; }
wait "$BP"
. "$DARLING_SRC_DIR/build-freebsd/series-count.sh"
series_count "$DARLING_BUILD_DIR" "$P" "$N" || exit 1
top="rc?x0"
[ -n "$rcs" ] && top=$(printf '%s\n' $rcs | sort | uniq -c | sort -rn | awk 'NR==1{print "rc" $2 "x" $1}')
if [ -n "$fwdlist" ]; then echo "FWDMISS $(printf '%s\n' "$fwdlist" | paste -sd, - | sed 's/,/, /g')"; else echo "FWDMISS none"; fi
# rc124 classifier: one NOWINDOW-DIAG line per run that hit the timeout (see nowindow-diag.sh analyze: where the main
# thread is, wayland connected, windows seen, last stage reached, the NSAlert text if any, and a one-word verdict)
_i=1
while [ "$_i" -le "$N" ]; do
	_L="$DARLING_BUILD_DIR/chrome-sr-$P$_i.log"; _i=$((_i+1))
	[ -f "$_L" ] || continue
	[ "$(sed -n 's/^WRAPPER_RC=//p' "$_L" | tail -1)" = 124 ] || continue
	echo "run $((_i-1)): $(sh "$DARLING_SRC_DIR/build-freebsd/nowindow-diag.sh" analyze "$_L" 2>&1 | tail -1)"
done
SERIES_LINE="SERIES $P N=$N valid=$valid survived20=$surv top=$top windows=$wins fwdmiss=$fwdmiss mldr=$M args=\"$CHROME_EXTRA_ARGS\""
echo "$SERIES_LINE"
series_summary_write "$DARLING_BUILD_DIR" "$P" "$N" "$SERIES_LINE" || echo "SERIES-SUMMARY-WRITE-FAILED"
# compress this run's big logs (>10M) after counting; the SERIES line above is unchanged
if command -v xz >/dev/null 2>&1; then find "$DARLING_BUILD_DIR" -maxdepth 1 -name "chrome-sr-$P*.log" -size +10M -exec xz -f {} + 2>/dev/null; fi
[ "$valid" -gt 0 ]
